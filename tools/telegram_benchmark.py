#!/usr/bin/env python3
"""Run the full Telegram benchmark matrix and generate the report.

This is the single entry point for the published Telegram page. It holds the
core lease for the whole matrix, runs the engine-only and Python points, writes
the raw JSON under var/, and invokes tools/telegram_report.py.

    python3 tools/telegram_benchmark.py --cpu-list 0,2,4,6 --repeat 5 --warmup-seconds 2
    python3 tools/telegram_benchmark.py --from-results \
        --results-dir var/bench-results/telegram

The HTML twin is generated by the report step and is gitignored. Raw JSON is
never committed.
"""

from __future__ import annotations

import argparse
import fcntl
import json
import os
import platform
import shutil
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH_BIN = ROOT / "target" / "release" / "examples" / "bench"
PY_BENCH = ROOT / "tools" / "bench_python.py"
REPORT = ROOT / "tools" / "telegram_report.py"
DEFAULT_RESULTS = ROOT / "var" / "bench-results" / "telegram"
DEFAULT_CPUS = "0,2,4,6"
PATTERN = r"@[a-zA-Z][a-zA-Z0-9_]{4,31}"
ENGINE_MODES = ("ucs", "bytes", "str")
PY_ENGINES = ("unirex", "re")


class CoreLease:
    """Advisory exclusive lease for the benchmark cores."""

    def __init__(self, path: Path, wait: float, cpus: list[int]):
        self.path = path
        self.wait = wait
        self.cpus = cpus
        self.file = None

    def __enter__(self):
        self.file = open(self.path, "a+", encoding="utf-8")
        try:
            os.chmod(self.path, 0o666)
        except OSError:
            pass
        deadline = time.monotonic() + self.wait
        while True:
            try:
                fcntl.flock(self.file.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except BlockingIOError:
                owner = self._owner()
                if time.monotonic() >= deadline:
                    raise SystemExit(
                        f"core lease {self.path} is busy after {self.wait:.0f}s; "
                        f"owner: {owner}"
                    )
                print(
                    f"waiting for core lease {self.path}; owner: {owner}",
                    file=sys.stderr,
                )
                time.sleep(1)
        self.file.seek(0)
        self.file.truncate()
        json.dump(
            {
                "user": os.environ.get("USER", ""),
                "pid": os.getpid(),
                "host": platform.node(),
                "cpus": self.cpus,
                "start": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
                "command": " ".join(sys.argv),
            },
            self.file,
        )
        self.file.flush()
        return self

    def _owner(self) -> str:
        try:
            self.file.seek(0)
            value = self.file.read().strip()
            self.file.seek(0, os.SEEK_END)
            return value or "<unknown>"
        except OSError:
            return "<unknown>"

    def __exit__(self, _exc_type, _exc, _tb):
        if self.file is not None:
            try:
                fcntl.flock(self.file.fileno(), fcntl.LOCK_UN)
            finally:
                self.file.close()
        return False


def parse_int_list(value: str, what: str) -> list[int]:
    result: list[int] = []
    for part in value.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            start_text, end_text = part.split("-", 1)
            start, end = int(start_text), int(end_text)
            if start > end:
                raise SystemExit(f"invalid {what} range {part!r}")
            result.extend(range(start, end + 1))
        else:
            result.append(int(part))
    if not result:
        raise SystemExit(f"empty {what} list")
    return sorted(set(result))


def cpu_name() -> str:
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as stream:
            for line in stream:
                if line.startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or platform.machine()


def find_cargo() -> str | None:
    candidate = os.environ.get("CARGO")
    if candidate:
        return candidate
    found = shutil.which("cargo")
    if found:
        return found
    fallback = Path.home() / ".cargo" / "bin" / "cargo"
    return str(fallback) if fallback.exists() else None


def rustc_version() -> str:
    candidates = [
        os.environ.get("RUSTC"),
        shutil.which("rustc"),
        str(Path.home() / ".cargo" / "bin" / "rustc"),
    ]
    for candidate in candidates:
        if not candidate:
            continue
        try:
            output = subprocess.run(
                [candidate, "--version"],
                check=True,
                capture_output=True,
                text=True,
            ).stdout.strip()
            if output:
                return output
        except (OSError, subprocess.CalledProcessError):
            continue
    return "unknown"


def detect_commit() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "workspace snapshot"


def build_all() -> None:
    cargo = find_cargo()
    if cargo is None:
        raise SystemExit(
            "cargo not found; install Rust or set CARGO, or build manually and rerun"
        )
    commands = [
        [cargo, "build", "--release", "--example", "bench"],
        [cargo, "build", "--release", "--features", "extension-module"],
    ]
    for command in commands:
        print("+", " ".join(command), flush=True)
        subprocess.run(command, cwd=ROOT, check=True)
    target = ROOT / "target" / "release"
    module = None
    for name in ("libunirex.so", "libunirex.dylib"):
        candidate = target / name
        if candidate.exists():
            module = candidate
            break
    if module is None:
        raise SystemExit(f"built extension not found under {target}")
    destination = ROOT / "var" / "py" / "unirex.so"
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(module, destination)
    print(f"copied {module} to {destination}", flush=True)


def check_prerequisites() -> None:
    missing = []
    if not BENCH_BIN.exists():
        missing.append(
            f"{BENCH_BIN.relative_to(ROOT)} (run "
            "`cargo build --release --example bench`)"
        )
    extension = ROOT / "var" / "py" / "unirex.so"
    if not extension.exists():
        missing.append(
            f"{extension.relative_to(ROOT)} (run "
            "`cargo build --release --features extension-module` and copy "
            "the shared object to var/py/unirex.so)"
        )
    if missing:
        raise SystemExit("missing prerequisites:\n  " + "\n  ".join(missing))


def run_command(command: list[str], env: dict | None = None) -> None:
    print("+", " ".join(command), flush=True)
    subprocess.run(command, cwd=ROOT, env=env, check=True)


def engine_command(
    mode: str,
    threads: int,
    args: argparse.Namespace,
    output: Path,
) -> list[str]:
    command = [
        str(BENCH_BIN),
        "--no-lock",
        "--mode",
        mode,
        "--threads",
        str(threads),
        "--cpu-list",
        args.cpu_list,
        "--warmup",
        "1",
        "--warmup-seconds",
        str(args.warmup_seconds),
        "--repeat",
        str(args.repeat),
        "--min-efficiency",
        str(args.min_efficiency),
        "--retries",
        str(args.retries),
        "--json",
        str(output),
    ]
    if args.corpus:
        command.extend(["--corpus", str(args.corpus)])
    if args.limit:
        command.extend(["--limit", str(args.limit)])
    return command


def python_command(
    engine: str,
    threads: int,
    args: argparse.Namespace,
    output: Path,
) -> list[str]:
    command = [
        sys.executable,
        str(PY_BENCH),
        "--engine",
        engine,
        "--threads",
        str(threads),
        "--cpu-list",
        args.cpu_list,
        "--warmup",
        "1",
        "--warmup-seconds",
        str(args.warmup_seconds),
        "--repeat",
        str(args.repeat),
        "--min-efficiency",
        str(args.min_efficiency),
        "--retries",
        str(args.retries),
        "--no-lock",
        "--json",
        str(output),
    ]
    if args.corpus:
        command.extend(["--corpus", str(args.corpus)])
    if args.limit:
        command.extend(["--limit", str(args.limit)])
    return command


def python_environment() -> dict:
    env = os.environ.copy()
    existing = env.get("PYTHONPATH")
    local = str(ROOT / "var" / "py")
    env["PYTHONPATH"] = local if not existing else local + os.pathsep + existing
    return env


def write_manifest(
    results_dir: Path,
    args: argparse.Namespace,
    threads: list[int],
    cpus: list[int],
    commit: str,
) -> None:
    manifest = {
        "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "host": platform.node(),
        "cpu": cpu_name(),
        "os": platform.platform(),
        "python": sys.version.split()[0],
        "rustc": rustc_version(),
        "commit": commit,
        "pattern": PATTERN,
        "threads": threads,
        "cpu_list": cpus,
        "cpu_list_text": args.cpu_list,
        "repeat": args.repeat,
        "warmup": 1,
        "warmup_seconds": args.warmup_seconds,
        "min_efficiency": args.min_efficiency,
        "retries": args.retries,
        "limit": args.limit,
        "corpus": str(args.corpus) if args.corpus else None,
        "files": sorted(
            path.name for path in results_dir.glob("*.json") if path.name != "manifest.json"
        ),
    }
    (results_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"wrote {results_dir / 'manifest.json'}", flush=True)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results-dir", type=Path, default=DEFAULT_RESULTS)
    parser.add_argument("--cpu-list", default=DEFAULT_CPUS)
    parser.add_argument("--threads", default="1,2,3,4")
    parser.add_argument("--repeat", type=int, default=5)
    parser.add_argument("--warmup-seconds", type=float, default=2.0)
    parser.add_argument("--min-efficiency", type=float, default=0.90)
    parser.add_argument("--retries", type=int, default=2)
    parser.add_argument("--limit", type=int)
    parser.add_argument("--corpus", type=Path)
    parser.add_argument("--lock", type=Path, default=Path("/tmp/core4.lock"))
    parser.add_argument("--lock-wait", type=float, default=600.0)
    parser.add_argument("--no-lock", action="store_true")
    parser.add_argument("--commit")
    parser.add_argument("--build", action="store_true")
    parser.add_argument("--from-results", action="store_true")
    parser.add_argument("--no-render", action="store_true")
    parser.add_argument("--no-html", action="store_true")
    parser.add_argument("--keep", action="store_true")
    args = parser.parse_args()

    threads = parse_int_list(args.threads, "thread")
    cpus = parse_int_list(args.cpu_list, "CPU")
    if args.repeat < 1:
        raise SystemExit("--repeat must be positive")
    if args.threads and max(threads) > len(cpus):
        raise SystemExit("--threads requests more workers than --cpu-list provides")
    if args.warmup_seconds < 0:
        raise SystemExit("--warmup-seconds must be non-negative")

    results_dir = args.results_dir
    if args.from_results:
        if not results_dir.is_dir():
            raise SystemExit(f"results directory not found: {results_dir}")
        if not args.no_render:
            run_command(
                [
                    sys.executable,
                    str(REPORT),
                    "--results-dir",
                    str(results_dir),
                    *(["--no-html"] if args.no_html else []),
                ]
            )
        return 0

    if args.build:
        build_all()
    check_prerequisites()

    results_dir.mkdir(parents=True, exist_ok=True)
    if not args.keep:
        for path in results_dir.glob("*.json"):
            path.unlink()

    commit = args.commit or detect_commit()
    lease = None
    if not args.no_lock:
        lease = CoreLease(args.lock, args.lock_wait, cpus)
        lease.__enter__()
    try:
        for mode in ENGINE_MODES:
            for worker_count in threads:
                output = results_dir / f"engine-{mode}-{worker_count}t.json"
                print(f"=== engine {mode} {worker_count}t ===", flush=True)
                run_command(engine_command(mode, worker_count, args, output))
        for engine in PY_ENGINES:
            for worker_count in threads:
                output = results_dir / f"python-{engine}-{worker_count}t.json"
                print(f"=== python {engine} {worker_count}t ===", flush=True)
                run_command(
                    python_command(engine, worker_count, args, output),
                    env=python_environment(),
                )
        write_manifest(results_dir, args, threads, cpus, commit)
        if args.limit is not None:
            print(
                "partial run requested with --limit; skipping report rendering",
                file=sys.stderr,
            )
        elif not args.no_render:
            run_command(
                [
                    sys.executable,
                    str(REPORT),
                    "--results-dir",
                    str(results_dir),
                    *(["--no-html"] if args.no_html else []),
                ]
            )
    finally:
        if lease is not None:
            lease.__exit__(None, None, None)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

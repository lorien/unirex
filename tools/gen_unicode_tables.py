#!/usr/bin/env python3
"""Generate `src/unicode_tables.rs` from CPython's own `re` tables.

The engine must agree with CPython `re`, not with Rust `regex`, so the ranges
come from `re` itself: every code point is tested against a compiled `\\w`,
`\\d`, and `\\s`, and the resulting ranges are emitted as sorted pair arrays.

    python3 tools/gen_unicode_tables.py            # rewrite the table file
    python3 tools/gen_unicode_tables.py --check    # fail if the file is stale

The file records the CPython version and `unicodedata.unidata_version` it was
generated from, so a divergence is attributable.
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "unicode_tables.rs"
MAX = 0x110000


def version_tuple() -> tuple[int, int, int]:
    return sys.version_info[:3]


def recorded_unicode_version() -> str | None:
    if not OUT.exists():
        return None
    for line in OUT.read_text().splitlines()[:6]:
        marker = "Unicode "
        if marker in line:
            return line.split(marker, 1)[1].rstrip(".").strip()
    return None


def ranges_for(pattern: str) -> list[tuple[int, int]]:
    rx = re.compile(pattern)
    text = "".join(chr(cp) for cp in range(MAX))
    hits = [m.start() for m in rx.finditer(text)]
    ranges: list[tuple[int, int]] = []
    for cp in hits:
        if ranges and ranges[-1][1] + 1 == cp:
            ranges[-1] = (ranges[-1][0], cp)
        else:
            ranges.append((cp, cp))
    return ranges


def render(name: str, ranges: list[tuple[int, int]]) -> list[str]:
    lines = [f"pub(crate) const {name}: &[(u32, u32)] = &["]
    for lo, hi in ranges:
        lines.append(f"    (0x{lo:04X}, 0x{hi:04X}),")
    lines.append("];")
    return lines


def fold_pairs() -> list[tuple[int, int]]:
    """Code-point pairs that match each other under CPython `re.IGNORECASE`.

    Candidates come from single-character lower/upper/title/casefold variants
    plus the special pairs CPython resolves itself: `i`/`\u0130`, `i`/`\u0131`,
    `s`/`\u017F`, `k`/`\u212A`, and `\u00DF`/`\u1E9E`. Every candidate is then
    validated with `re.IGNORECASE`, so a wrong guess cannot reach the table.
    """
    specials = [
        ("i", "\u0130"),
        ("i", "\u0131"),
        ("I", "\u0131"),
        ("s", "\u017F"),
        ("S", "\u017F"),
        ("k", "\u212A"),
        ("K", "\u212A"),
        ("\u00DF", "\u1E9E"),
    ]
    candidates: set[tuple[int, int]] = set()
    for cp in range(MAX):
        ch = chr(cp)
        for form in (ch.lower(), ch.upper(), ch.title(), ch.casefold()):
            if len(form) == 1 and form != ch:
                candidates.add((cp, ord(form)))
    for left, right in specials:
        candidates.add((ord(left), ord(right)))
        candidates.add((ord(right), ord(left)))

    kept = []
    for a, b in sorted(candidates):
        pattern = re.compile("^" + re.escape(chr(a)) + "$", re.IGNORECASE)
        if pattern.match(chr(b)):
            kept.append((a, b))
    return kept


def build() -> str:
    word = ranges_for(r"\w")
    digit = ranges_for(r"\d")
    space = ranges_for(r"\s")
    lines = [
        "//! Generated by `tools/gen_unicode_tables.py`. Do not edit by hand.",
        "//!",
        f"//! CPython {version_tuple()[0]}.{version_tuple()[1]}, Unicode {unicodedata.unidata_version}.",
        "//!",
        "//! Each table is a sorted list of inclusive ranges of code points that the",
        "//! corresponding CPython `re` class matches. The engine matches CPython `re`",
        "//! semantics, so these come from `re` itself rather than from Rust `regex` or",
        "//! from `unicodedata` predicates, which differ at the edges.",
        "",
    ]
    lines.extend(render("WORD", word))
    lines.append("")
    lines.extend(render("DIGIT", digit))
    lines.append("")
    lines.extend(render("SPACE", space))
    lines.append("")
    lines.extend(render("FOLD", fold_pairs()))
    lines.append("")
    lines.append("/// Whether `code_point` is a `\\w` unit in CPython `re`.")
    lines.append("pub(crate) fn is_word(code_point: u32) -> bool {")
    lines.append("    contains(WORD, code_point)")
    lines.append("}")
    lines.append("")
    lines.append("/// Ranges for `WORD`, `DIGIT`, and `SPACE` looked up by binary search.")
    lines.append("fn contains(ranges: &[(u32, u32)], code_point: u32) -> bool {")
    lines.append("    ranges")
    lines.append("        .binary_search_by(|&(lo, hi)| {")
    lines.append("            if code_point < lo {")
    lines.append("                std::cmp::Ordering::Greater")
    lines.append("            } else if code_point > hi {")
    lines.append("                std::cmp::Ordering::Less")
    lines.append("            } else {")
    lines.append("                std::cmp::Ordering::Equal")
    lines.append("            }")
    lines.append("        })")
    lines.append("        .is_ok()")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = build()
    if args.check:
        recorded = recorded_unicode_version()
        if recorded != unicodedata.unidata_version:
            # Content depends on the Unicode database, which is a property of
            # the interpreter, not of this repository. Comparing across
            # versions would report drift that the repository cannot fix.
            print(
                f"{OUT}: skipping content check, table records Unicode {recorded} "
                f"and this interpreter has {unicodedata.unidata_version}"
            )
            return 0
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run tools/gen_unicode_tables.py")
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
